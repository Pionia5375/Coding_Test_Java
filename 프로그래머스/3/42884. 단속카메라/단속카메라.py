def solution(routes):
    routes.sort()                    # 진입 지점 기준 오름차순
    answer = 1
    _, e = routes[0]                 # 현재 묶음의 교집합 끝점

    for start, end in routes[1:]:
        if start <= e:               # 겹침 -> 교집합으로 좁힘
            e = min(e, end)
        else:                        # 안 겹침 -> 새 카메라
            answer += 1
            e = end

    return answer
# 구하고자 하는 값: 모든 차량을 단속할 수 있는 카메라의 최소 개수
# 입력: 각 요소는 차량을 의미. 0번째는 진입, 1번째는 진출

